export type Dict = typeof en;
const dictionaries: Record<Language, Dict> = { en, vi };

export const t = (lang: Language): Dict => dictionaries[lang];

export function detectLanguage(): Language {
  const saved = typeof localStorage !== "undefined" ? localStorage.getItem("cb.lang") : null;
  if (saved === "en" || saved === "vi") return saved;
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("vi") ? "vi" : "en";
}
